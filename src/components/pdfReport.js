function recommendationPage(doc, data) {
  const { analysis, aiSummary } = data;

  let y = PAGE.top;

  y = sectionTitle(doc, "6. AI Insights & Recommendations", y);

  y = paragraph(
    doc,
    "The AI engine analysed the uploaded dataset and generated the following observations and recommendations based on detected quality issues, business opportunities and overall dataset readiness.",
    y
  );

  const addBulletSection = (title, items, numbered = false) => {
    y += 8;
    y = ensurePage(doc, y, 25);
    y = sectionTitle(doc, title, y);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(FONT.body);
    doc.setTextColor(70);

    items.forEach((item, index) => {
      const prefix = numbered
        ? `${index + 1}. `
        : "• ";

      const lines = doc.splitTextToSize(
        prefix + item,
        PAGE.contentWidth
      );

      y = ensurePage(doc, y, lines.length * 6 + 8);

      doc.text(
        lines,
        PAGE.margin,
        y
      );

      y += lines.length * 6 + 2;
    });
  };

  addBulletSection(
    "Key Risks",
    aiSummary?.risks?.length
      ? aiSummary.risks
      : [
          "No major risks were identified in the uploaded dataset."
        ]
  );

  addBulletSection(
    "Business Opportunities",
    aiSummary?.opportunities?.length
      ? aiSummary.opportunities
      : [
          "No significant business opportunities were detected."
        ]
  );

  addBulletSection(
    "AI Recommendations",
    analysis.recommendations?.length
      ? analysis.recommendations
      : [
          "No AI recommendations are available."
        ],
    true
  );

  addBulletSection(
    "Recommended Action Plan",
    aiSummary?.actions?.length
      ? aiSummary.actions
      : [
          "Clean missing values.",
          "Remove duplicate records.",
          "Validate important fields.",
          "Re-run quality assessment.",
          "Monitor dataset quality regularly."
        ],
    true
  );

  y += 8;

  y = sectionTitle(
    doc,
    "Executive Recommendation",
    y
  );

  let conclusion = "";

  if (analysis.analysis.quality_score >= 90) {
    conclusion =
      "The uploaded dataset is considered highly reliable and suitable for executive reporting, predictive analytics and AI-driven decision making with only minimal preprocessing.";
  } else if (analysis.analysis.quality_score >= 75) {
    conclusion =
      "The dataset is suitable for business analysis after minor cleaning and validation. Implementing the recommendations above will improve confidence in future analytical outcomes.";
  } else {
    conclusion =
      "The dataset requires comprehensive cleansing and validation before it should be used for operational reporting or strategic business decisions.";
  }

  y = paragraph(doc, conclusion, y);

  doc.addPage();
}
