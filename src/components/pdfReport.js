import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

const PAGE = {
  width: 210,
  height: 297,
  margin: 20,
  top: 30,
  bottom: 20,
  contentWidth: 170,
};

const FONT = {
  title: 24,
  heading: 16,
  subHeading: 13,
  body: 10,
  small: 8,
};

function ensurePage(doc, y, required = 25) {
  if (y + required > PAGE.height - 30) {
    doc.addPage();
    return PAGE.top;
  }
  return y;
}

function addHeader(doc) {
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(20);

  doc.text(
    "AI Innovation Radar",
    PAGE.margin,
    10
  );

  doc.setFont("helvetica", "normal");
  doc.setTextColor(100);

  doc.text(
    "Executive Intelligence Report",
    PAGE.width - PAGE.margin,
    10,
    {
      align: "right",
    }
  );

  doc.setDrawColor(190);

  doc.line(
    PAGE.margin,
    14,
    PAGE.width - PAGE.margin,
    14
  );
}

function addFooter(doc, page, total) {
  doc.setDrawColor(190);

  doc.line(
    PAGE.margin,
    282,
    PAGE.width - PAGE.margin,
    282
  );

  doc.setFont("helvetica", "normal");
  doc.setFontSize(8);
  doc.setTextColor(120);

  doc.text(
    "Generated by AI Innovation Radar",
    PAGE.margin,
    288
  );

  doc.text(
    new Date().toLocaleString(),
    PAGE.width / 2,
    288,
    {
      align: "center",
    }
  );

  doc.text(
    `Page ${page} of ${total}`,
    PAGE.width - PAGE.margin,
    288,
    {
      align: "right",
    }
  );
}

function applyHeaderFooter(doc) {
  const total = doc.getNumberOfPages();

  for (let i = 1; i <= total; i++) {
    doc.setPage(i);

    addHeader(doc);

    addFooter(doc, i, total);
  }
}

function sectionTitle(doc, title, y) {
  y = ensurePage(doc, y, 18);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(FONT.heading);
  doc.setTextColor(20);

  doc.text(
    title,
    PAGE.margin,
    y
  );

  doc.setDrawColor(200);

  doc.line(
    PAGE.margin,
    y + 4,
    PAGE.width - PAGE.margin,
    y + 4
  );

  return y + 12;
}

function paragraph(doc, text, y) {
  y = ensurePage(doc, y, 20);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(FONT.body);
  doc.setTextColor(70);

  const lines = doc.splitTextToSize(
    text,
    PAGE.contentWidth
  );

  doc.text(
    lines,
    PAGE.margin,
    y
  );

  return y + lines.length * 6;
}

function createTable(doc, options) {
  autoTable(doc, {
    theme: "grid",

    pageBreak: "auto",

    rowPageBreak: "avoid",

    margin: {
      top: 35,
      bottom: 22,
      left: PAGE.margin,
      right: PAGE.margin,
    },

    styles: {
      font: "helvetica",
      fontSize: 9,
      cellPadding: 3,
      textColor: 40,
      lineColor: 190,
      lineWidth: 0.2,
      overflow: "linebreak",
    },

    headStyles: {
      fillColor: [255, 255, 255],
      textColor: 20,
      fontStyle: "bold",
      lineColor: 130,
      lineWidth: 0.4,
    },

    alternateRowStyles: {
      fillColor: [248, 248, 248],
    },

    ...options,
  });
}



