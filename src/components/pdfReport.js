function sentimentPage(doc, data) {

  const { sentiment } = data;

  if (!sentiment?.available) {
    return;
  }

  let y = 30;

  sectionTitle(
    doc,
    "4. Customer Sentiment Analysis",
    y
  );

  y = 48;

  paragraph(
    doc,
    "This section summarizes the sentiment detected within the uploaded dataset. The AI engine classified each observation into Positive, Neutral and Negative categories to provide an overview of customer perception.",
    y
  );

  y += 18;

  autoTable(doc, {

    startY: y,

    theme: "grid",

    head: [["Sentiment", "Count"]],

    body: [

      ["Positive", sentiment.positive],

      ["Neutral", sentiment.neutral],

      ["Negative", sentiment.negative],

    ],

    styles: {

      font: "helvetica",

      fontSize: 10,

      cellPadding: 4,

      textColor: 40,

      lineColor: 180,

      lineWidth: .2

    },

    headStyles: {

      fillColor: [255,255,255],

      textColor: 20,

      fontStyle: "bold",

      lineColor: 120,

      lineWidth: .4

    },

    alternateRowStyles: {

      fillColor: [248,248,248]

    },

    margin: {

      left: PAGE.margin,

      right: PAGE.margin

    }

  });

  y = doc.lastAutoTable.finalY + 18;

  sectionTitle(
    doc,
    "Interpretation",
    y
  );

  y += 12;

  const total =
    sentiment.positive +
    sentiment.neutral +
    sentiment.negative;

  const positive =
    ((sentiment.positive / total) * 100).toFixed(1);

  const neutral =
    ((sentiment.neutral / total) * 100).toFixed(1);

  const negative =
    ((sentiment.negative / total) * 100).toFixed(1);

  paragraph(
    doc,
    `The sentiment analysis indicates that ${positive}% of the analysed records were classified as Positive, ${neutral}% as Neutral and ${negative}% as Negative. This distribution provides a high-level view of customer perception and can assist management in identifying areas requiring attention. While the majority sentiment reflects the overall customer experience, negative observations should be reviewed individually to understand the underlying causes and improve future business performance.`,
    y
  );

  y += 45;

  sectionTitle(
    doc,
    "Executive Observation",
    y
  );

  y += 12;

  let observation = "";

  if (sentiment.positive >= sentiment.neutral &&
      sentiment.positive >= sentiment.negative) {

    observation =
      "Customer sentiment is predominantly positive, indicating a generally favourable response. Continuous monitoring is recommended to maintain customer satisfaction while addressing isolated negative feedback.";

  } else if (sentiment.negative >= sentiment.positive) {

    observation =
      "Negative sentiment represents the largest share of responses. Management should investigate recurring concerns and prioritise corrective actions to improve customer experience.";

  } else {

    observation =
      "The sentiment distribution is relatively balanced, suggesting mixed customer experiences. Further analysis of individual responses is recommended before drawing strategic conclusions.";

  }

  paragraph(
    doc,
    observation,
    y
  );

  doc.addPage();

}
